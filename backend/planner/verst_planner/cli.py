"""Command line: ``python3 -m verst_planner.cli plan|share|export-config``.

``plan --world W --input I [--clock ISO] [--events] [--out F]`` prints the public plan JSON (A§10.3 shape);
with ``--events`` one JSON line per progress event goes to stderr. ``--input`` accepts a bare TripInputDTO or
a golden case file (``input``, optional ``clock`` and ``config``). ``share`` prints the share text.
``export-config`` prints the SQL seed of ``core.app_config`` (``planner`` and ``reasons_ru``).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from datetime import datetime
from pathlib import Path
from typing import Any, TextIO

from verst_planner import resources
from verst_planner.adapters.fake import GOLDEN_CLOCK, FakeWorld, build_fakes
from verst_planner.config import PlannerConfig
from verst_planner.domain import codec
from verst_planner.domain.model import TripPlan
from verst_planner.engine import Planner
from verst_planner.events import PlanEvent, event_to_json
from verst_planner.explain.share import share_text
from verst_planner.explain.templates import ReasonTemplates


class _StderrSink:
    def __init__(self, stream: TextIO) -> None:
        self.stream = stream

    def emit(self, event: PlanEvent) -> None:
        self.stream.write(json.dumps(event_to_json(event), ensure_ascii=False) + "\n")


def read_file(path: str | Path) -> str:
    """UTF-8 text of a file given on a command line (also used by `mobile selftest --world`)."""
    return Path(path).read_text(encoding="utf-8")


def _plan(args: argparse.Namespace, events: TextIO | None) -> TripPlan:
    with Path(args.input).open(encoding="utf-8") as f:
        doc: dict[str, Any] = json.load(f)
    raw_input = doc.get("input", doc)
    clock_s = args.clock or doc.get("clock")
    now = datetime.fromisoformat(clock_s) if clock_s else GOLDEN_CLOCK
    fakes = build_fakes(FakeWorld.load(args.world), now)
    planner = Planner(
        routing=fakes.routing,
        places=fakes.places,
        prices=fakes.prices,
        tolls=fakes.tolls,
        regions=fakes.regions,
        geocoding=fakes.geocoding,
        clock=fakes.clock,
        config=PlannerConfig.from_dict(doc.get("config") or {}),
        templates=ReasonTemplates.default(),
    )
    sink = _StderrSink(events) if events is not None else None
    if sink is None:
        return planner.plan(codec.input_from_json(raw_input))
    return planner.plan(codec.input_from_json(raw_input), sink)


def export_config_sql() -> str:
    """`INSERT … ON CONFLICT` rows for `core.app_config` from the shipped resources (DEV-021 seed)."""
    rows = []
    for key, name in (("planner", "planner_config.json"), ("reasons_ru", "reasons.ru.json")):
        value = json.dumps(json.loads(resources.read_text(name)), ensure_ascii=False, sort_keys=True)
        literal = value.replace("'", "''")
        rows.append(
            "INSERT INTO core.app_config (key, value, updated_by)\n"
            f"  VALUES ('{key}', '{literal}'::jsonb, 'seed')\n"
            f"  ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = now(), "
            f"updated_by = EXCLUDED.updated_by;"
        )
    header = "-- Generated by: python3 -m verst_planner.cli export-config (do not edit by hand)\n"
    return header + "\n".join(rows) + "\n"


def main(
    argv: Sequence[str] | None = None, stdout: TextIO | None = None, stderr: TextIO | None = None
) -> int:
    out = stdout or sys.stdout
    err = stderr or sys.stderr
    parser = argparse.ArgumentParser(prog="verst_planner.cli")
    sub = parser.add_subparsers(dest="cmd", required=True)
    for name in ("plan", "share"):
        p = sub.add_parser(name)
        p.add_argument("--world", required=True)
        p.add_argument("--input", required=True)
        p.add_argument("--clock")
        if name == "plan":
            p.add_argument("--events", action="store_true")
            p.add_argument("--out")
    sub.add_parser("export-config")
    args = parser.parse_args(argv)
    if args.cmd == "export-config":
        out.write(export_config_sql())
        return 0
    if args.cmd == "share":
        out.write(share_text(_plan(args, None)) + "\n")
        return 0
    plan = _plan(args, err if args.events else None)
    text = json.dumps(codec.plan_to_json(plan), ensure_ascii=False, indent=2) + "\n"
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    else:
        out.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
