#!/usr/bin/env python3
"""DES-102: design/icons/*.svg -> android/core-ui/src/main/res/drawable/ic_<name>.xml (VectorDrawable).

Each icon (generated by gen_icons.py) is one nonzero-filled path in a 24 x 24 viewBox. The output keeps
the path data verbatim (whitespace-normalised; asserted), 24 dp, fill #FF141416 (tinted at use, signs.md §3).

Usage:  python3 design/tools/gen_vectors.py          write the drawables
        python3 design/tools/gen_vectors.py --check  exit 0 if current, 1 with a diff otherwise
"""
from __future__ import annotations

import difflib
import glob
import os
import re
import sys
import xml.dom.minidom

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ICONS = os.path.join(ROOT, 'design', 'icons')
OUT = os.path.join(ROOT, 'android', 'core-ui', 'src', 'main', 'res', 'drawable')
FILL = '#FF141416'  # color.sign.black

TEMPLATE = ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- GENERATED from design/icons/{src} by design/tools/gen_vectors.py. Do not edit. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n'
            '    android:height="24dp"\n'
            '    android:viewportWidth="24"\n'
            '    android:viewportHeight="24">\n'
            '    <path\n'
            '        android:fillColor="{fill}"\n'
            '        android:fillType="nonZero"\n'
            '        android:pathData="{d}" />\n'
            '</vector>\n')


def norm(d: str) -> str:
    return re.sub(r'\s+', ' ', d).strip()


def convert(svg_path: str) -> tuple[str, str]:
    dom = xml.dom.minidom.parse(svg_path)
    svg = dom.documentElement
    assert svg.getAttribute('viewBox') == '0 0 24 24', '%s: viewBox must be 0 0 24 24' % svg_path
    paths = dom.getElementsByTagName('path')
    assert len(paths) == 1, '%s: exactly one <path> expected' % svg_path
    assert not dom.getElementsByTagName('image') and not dom.getElementsByTagName('text'), svg_path
    assert not paths[0].getAttribute('stroke'), '%s: icons must be stroke-free' % svg_path
    d = norm(paths[0].getAttribute('d'))
    name = 'ic_' + os.path.basename(svg_path)[:-4].replace('-', '_')
    xml_text = TEMPLATE.format(src=os.path.basename(svg_path), fill=FILL, d=d)
    out_dom = xml.dom.minidom.parseString(xml_text.encode('utf-8'))
    out_d = out_dom.getElementsByTagName('path')[0].getAttribute('android:pathData')
    assert norm(out_d) == d, '%s: pathData differs from the SVG d attribute' % svg_path
    return name, xml_text


def main() -> int:
    check = '--check' in sys.argv
    sources = sorted(glob.glob(os.path.join(ICONS, '*.svg')))
    results = [convert(p) for p in sources]
    print('icons: %d svg -> %d drawables (pathData == d asserted)' % (len(sources), len(results)))
    if check:
        stale = False
        for name, text in results:
            path = os.path.join(OUT, name + '.xml')
            old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
            if old != text:
                stale = True
                rel = os.path.relpath(path, ROOT)
                sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True), rel + ' (committed)', rel + ' (generated)'))
        print('gen_vectors --check: %s' % ('STALE' if stale else 'up to date'))
        return 1 if stale else 0
    os.makedirs(OUT, exist_ok=True)
    for name, text in results:
        open(os.path.join(OUT, name + '.xml'), 'w', encoding='utf-8').write(text)
    print('wrote %d files to %s' % (len(results), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
